#!/usr/bin/env node
/**
 * Creates the Android release keystore and the properties file that
 * android/app/build.gradle reads.
 *
 * Why this matters more than it looks
 * -----------------------------------
 * Android identifies an app by its package name *and* its signing key. It will
 * only install a new APK over an existing one -- keeping the user's
 * conversations, personas, voice models and API keys -- when the signature
 * matches. If the key changes, the install is refused; the only way forward is
 * to uninstall, which deletes all of that data.
 *
 * So this key is generated exactly once and then kept forever. Back up both
 * android/alterego-release.keystore and android/keystore.properties somewhere
 * that is not this working copy (both are gitignored). Losing them means every
 * existing user has to wipe and reinstall.
 *
 * The generated key is valid for 100 years, because an expired signing key
 * cannot be used to publish updates either.
 *
 * Usage:
 *   npm run android:keystore                 (prompts are avoided; see below)
 *   ANDROID_KEYSTORE_PASSWORD=... npm run android:keystore
 *
 * The password is taken from ANDROID_KEYSTORE_PASSWORD when set. Otherwise a
 * strong random one is generated and written to keystore.properties, which is
 * the file you must back up.
 */

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const androidDir = path.join(__dirname, '..', 'android');
const keystorePath = path.join(androidDir, 'alterego-release.keystore');
const propsPath = path.join(androidDir, 'keystore.properties');

const KEY_ALIAS = 'alterego';
const VALIDITY_DAYS = 36500; // ~100 years
const DNAME = 'CN=L4w1i3t, OU=ALTER EGO, O=L4w1i3t, L=Unknown, ST=Unknown, C=US';

function findKeytool() {
  // JAVA_HOME wins; otherwise trust PATH, which is how Android Studio sets it up.
  const fromJavaHome = process.env.JAVA_HOME
    ? path.join(
        process.env.JAVA_HOME,
        'bin',
        process.platform === 'win32' ? 'keytool.exe' : 'keytool'
      )
    : null;

  if (fromJavaHome && fs.existsSync(fromJavaHome)) return fromJavaHome;

  const probe = spawnSync('keytool', ['-help'], { stdio: 'ignore' });
  if (probe.error) {
    console.error(
      'keytool was not found. It ships with the JDK.\n' +
        'Set JAVA_HOME to your JDK (Android Studio bundles one under\n' +
        '  <Android Studio>/jbr\n' +
        ') or add its bin directory to PATH, then run this again.'
    );
    process.exit(1);
  }
  return 'keytool';
}

function main() {
  if (fs.existsSync(keystorePath)) {
    console.log(`A keystore already exists at:\n  ${keystorePath}`);
    console.log(
      '\nRefusing to overwrite it. Replacing a release key means existing\n' +
        'installs can no longer be updated in place and users would lose their\n' +
        'data. Delete it by hand only if you are certain nothing was ever\n' +
        'published with it.'
    );
    process.exit(0);
  }

  if (!fs.existsSync(androidDir)) {
    console.error(
      'android/ does not exist. Run `npx cap add android` first.'
    );
    process.exit(1);
  }

  const keytool = findKeytool();

  // base64url of 24 random bytes: no shell-quoting hazards in the password.
  const password =
    process.env.ANDROID_KEYSTORE_PASSWORD ||
    crypto.randomBytes(24).toString('base64url');
  const generated = !process.env.ANDROID_KEYSTORE_PASSWORD;

  console.log('Generating release keystore...');
  const result = spawnSync(
    keytool,
    [
      '-genkeypair',
      '-v',
      '-keystore', keystorePath,
      '-alias', KEY_ALIAS,
      '-keyalg', 'RSA',
      '-keysize', '4096',
      '-validity', String(VALIDITY_DAYS),
      '-storetype', 'PKCS12',
      '-storepass', password,
      '-keypass', password,
      '-dname', DNAME,
    ],
    { stdio: ['ignore', 'pipe', 'pipe'] }
  );

  if (result.status !== 0) {
    console.error('keytool failed:');
    console.error(result.stderr?.toString() || result.stdout?.toString());
    process.exit(1);
  }

  // storeFile is resolved by build.gradle relative to the android/ directory.
  const props =
    '# Generated by scripts/setup-android-keystore.js\n' +
    '#\n' +
    '# BACK THIS FILE UP, along with the .keystore it points at. Without them\n' +
    '# you cannot ship an update that existing users can install without first\n' +
    '# uninstalling -- which erases their conversations and personas.\n' +
    '#\n' +
    '# This file is gitignored on purpose. Never commit it.\n' +
    `storeFile=${path.basename(keystorePath)}\n` +
    `storePassword=${password}\n` +
    `keyAlias=${KEY_ALIAS}\n` +
    `keyPassword=${password}\n`;

  fs.writeFileSync(propsPath, props, { mode: 0o600 });

  console.log(`\nKeystore:   ${keystorePath}`);
  console.log(`Properties: ${propsPath}`);
  if (generated) {
    console.log(
      '\nA random password was generated and stored in keystore.properties.'
    );
  }
  console.log(
    '\nNext:\n' +
      '  1. Back up both files somewhere outside this repository.\n' +
      '  2. Build a signed APK with `npm run android:apk:release`.\n' +
      '\nNote: a release-signed APK cannot be installed over a debug-signed one.\n' +
      'If you already have a debug build on your phone, export your data first\n' +
      '(Settings -> Backup & Restore), uninstall, install the release APK, then\n' +
      'import the backup. Every later release update will preserve data in place.'
  );
}

main();
